#!/bin/sh
# kpm_verify.sh — Ed25519 signature verification for KPM modules.
#
# This file is intended to be sourced from service.sh (and any other
# caller that wants to verify a .kpm before loading it). It exposes
# one public function:
#
#   verify_kpm_sig <kpm_file> <sig_file>
#
# Behavior:
#   * Returns 0 (success) when the signature is valid.
#   * Returns 1 (failure) when verification fails for any reason
#     (missing sig file, bad sig format, signature mismatch, openssl
#     not present, etc.). The caller SHOULD log and skip loading the
#     module in that case.
#
# .kpm.sig file format (MVP):
#   The first non-empty line of the file is the 64-byte Ed25519
#   signature encoded as 128 lowercase hex characters, with no
#   whitespace. Any other lines are ignored. This keeps the file
#   grep-friendly and trivially parseable on Android shell.
#
# Public key:
#   KPM_SIGN_PUBKEY_HEX is a hardcoded 32-byte Ed25519 public key
#   encoded as 64 lowercase hex characters.
#   The current value is a DEV/TEST key. TODO(security): replace with
#   a release key managed out-of-band, and consider loading the key
#   from /data/adb/patchnest/kpm_sign_pubkey instead of hardcoding it.
#
# Tooling:
#   We use `openssl pkeyutl -verify -rawin` with a DER SubjectPublicKeyInfo
#   (SPKI) key to verify the original module bytes.
#
#   We intentionally avoid the BSD `signify` and any prebuilt NDK
#   crypto blob. If openssl is missing, verify_kpm_sig returns 1 and
#   the caller treats that as a verification failure (which is the
#   safe default when enforcement is on).
#
# Boot policy:
#   service.sh skips verification in off mode. Both warn and strict
#   reject a failed verification. For a missing signature, service.sh
#   handles the policy directly: warn logs and continues, strict skips.

# ---------- bundled public key ----------
# Generated locally for the v0.3.0 ultracode audit (2026-06-06).
# Replaces the previous RFC 8032 Test 1 key, which was the well-known
# "everyone has the private key" value — meaning anyone could forge
# a .kpm.sig that this verifier would accept.
#
# This key is the corresponding PUBLIC half of an Ed25519 pair
# generated by the maintainer on 2026-06-06. The matching private
# key is held out-of-band (NOT in this repo); use it via
#     openssl pkeyutl -sign -inkey <priv> -rawin -in <kpm> \
#                     -out <signature.bin>
# then hex-encode the signature for the .kpm.sig file.
KPM_SIGN_PUBKEY_HEX="a6cee3371d164daf9ad2ed38ecaf1d492e7867fc6df31f810e69eaa0dd45259b"

# ---------- internal helpers ----------

# kpm_verify__log <msg>
# Append a timestamped line to the service log when one is writable.
# Service.sh sets $PNDIR and $LOG; we tolerate their absence so that
# this script is safe to source from any context.
kpm_verify__log() {
    if [ -n "${LOG:-}" ] && [ -n "${PNDIR:-}" ] && [ -d "$PNDIR" ]; then
        printf '[%s] kpm_verify: %s\n' "$(date)" "$1" >> "$LOG" 2>/dev/null
    fi
}

# kpm_verify__hex_to_bin <hex_string> <out_file>
# Write the binary representation of <hex_string> to <out_file>.
# Returns 0 on success, 1 if the input is not valid hex of even length.
# This is intentionally written in pure POSIX shell (no awk ord(),
# no xxd, no perl) so it works on stock Android mksh/toybox/ash.
kpm_verify__hex_to_bin() {
    local _hex=$1
    local _out=$2
    local _rest _pair _byte _fmt _expected_sz _actual_sz
    # Reject any non-hex char early.
    case "$_hex" in
        *[!0-9a-fA-F]*) return 1 ;;
    esac
    if [ $(( ${#_hex} % 2 )) -ne 0 ]; then
        return 1
    fi
    _expected_sz=$(( ${#_hex} / 2 ))
    # POSIX printf %b accepts \0ooo, including NUL. Keep only the
    # escape sequences in shell variables and write the bytes once.
    _fmt=""
    while [ -n "$_hex" ]; do
        _rest=${_hex#??}
        _pair=${_hex%"$_rest"}
        _byte=$((0x${_pair}))
        _fmt="${_fmt}\\0$((_byte / 64))$((_byte / 8 % 8))$((_byte % 8))"
        _hex=$_rest
    done
    if ! printf '%b' "$_fmt" > "$_out" 2>/dev/null; then
        rm -f "$_out" 2>/dev/null
        return 1
    fi
    # Verify output size matches expected binary length.
    _actual_sz=$(wc -c < "$_out" 2>/dev/null) || return 1
    if ! [ "$_actual_sz" -eq "$_expected_sz" ]; then
        rm -f "$_out" 2>/dev/null
        return 1
    fi
    return 0
}

# ---------- public API ----------

# verify_kpm_sig <kpm_file> <sig_file>
# Returns 0 if the signature is valid, 1 otherwise.
verify_kpm_sig() (
    local _kpm=${1:-}
    local _sig=${2:-}
    local _sig_hex _tmpdir _pub_der _sig_bin

    if [ -z "$_kpm" ] || [ -z "$_sig" ]; then
        kpm_verify__log "missing arguments"
        return 1
    fi
    if [ ! -f "$_kpm" ]; then
        kpm_verify__log "kpm file not found: $_kpm"
        return 1
    fi
    if [ ! -f "$_sig" ]; then
        kpm_verify__log "sig file not found: $_sig"
        return 1
    fi

    if ! command -v openssl >/dev/null 2>&1; then
        kpm_verify__log "openssl not available; failing closed"
        return 1
    fi

    # Read the hex signature (first non-empty line) and validate.
    _sig_hex=$(awk 'NF{print; exit}' "$_sig" 2>/dev/null | tr -d ' \t\r\n')
    case ${#_sig_hex} in
        128) ;;
        *)
            kpm_verify__log "sig file is not 64 bytes (got ${#_sig_hex} hex chars)"
            return 1 ;;
    esac
    case "$_sig_hex" in
        *[!0-9a-fA-F]*)
            kpm_verify__log "sig file contains non-hex characters"
            return 1
            ;;
    esac

    if ! _tmpdir=$(mktemp -d "${TMPDIR:-/data/local/tmp}/kpm_verify.XXXXXX" 2>/dev/null) &&
       ! _tmpdir=$(mktemp -d /tmp/kpm_verify.XXXXXX 2>/dev/null); then
        kpm_verify__log "could not create temp dir"
        return 1
    fi
    # Traps belong to the verifier subshell, even when a caller sources us.
    trap 'rm -rf -- "$_tmpdir"' EXIT
    trap 'exit 1' HUP INT TERM
    _pub_der="$_tmpdir/pub.der"
    _sig_bin="$_tmpdir/sig.bin"

    # SPKI for Ed25519: algorithm OID 1.3.101.112 and a 32-byte BIT STRING.
    if [ "${#KPM_SIGN_PUBKEY_HEX}" -ne 64 ] ||
       ! kpm_verify__hex_to_bin "302a300506032b6570032100${KPM_SIGN_PUBKEY_HEX}" "$_pub_der"; then
        kpm_verify__log "could not encode bundled Ed25519 public key"
        return 1
    fi
    if ! kpm_verify__hex_to_bin "$_sig_hex" "$_sig_bin"; then
        kpm_verify__log "sig hex decode failed"
        return 1
    fi

    if openssl pkeyutl -verify -pubin -keyform DER -inkey "$_pub_der" \
            -rawin -in "$_kpm" -sigfile "$_sig_bin" >/dev/null 2>&1; then
        kpm_verify__log "signature OK: $(basename "$_kpm")"
        return 0
    fi
    kpm_verify__log "signature INVALID: $(basename "$_kpm")"
    return 1
)
